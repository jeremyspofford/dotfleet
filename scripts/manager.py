def prompt_style(name, text):
    """Reuse the palette exported by logger.sh; never invent another color scheme."""
    if 'NO_COLOR' in os.environ or os.environ.get('TERM') == 'dumb':
        return text
    color = os.environ.get(name, '')
    bold = os.environ.get('BOLD', '') if name == 'CYAN' else ''
    return color + bold + text + os.environ.get('CLEAR', '') if color else text


def ask(label, default, choices=None, defaults=False, *, detail='', heading=None, formatted=False):
    if defaults:
        return default
    try:
        with open('/dev/tty', 'r') as reader, open('/dev/tty', 'w') as terminal:
            while True:
                terminal.write('\n' + prompt_style('CYAN', heading or label) + '\n')
                terminal.write('-' * min(len(heading or label), 60) + '\n')
                if detail:
                    width = max(30, min(os.get_terminal_size(terminal.fileno()).columns or 80, 100))
                    for line in detail.splitlines():
                        indent = ' ' * 12 if line.startswith('  ') else ''
                        value = line if formatted else textwrap.fill(line, width, subsequent_indent=indent,
                                                     break_long_words=False, break_on_hyphens=False)
                        palette = {'+': 'GREEN', '−': 'RED', '~': 'YELLOW'}.get(change_marker(line)) if formatted else None
                        terminal.write((prompt_style(palette, value) if palette else value) + '\n')
                    terminal.write('\n')
                terminal.write(prompt_style('GREEN', f'{label} [{default}]: '))
                terminal.flush()
                answer = reader.readline()
                if not answer:
                    raise ValueError('Terminal input ended; no answer was accepted.')
                answer = answer.strip() or default
                if choices is None or answer in choices:
                    terminal.write('\n')
                    terminal.flush()
                    return answer
                terminal.write('\n' + prompt_style('YELLOW', 'Choose ' + ', '.join(choices) + '. Press Enter to submit.') + '\n')
    except OSError as error:
        raise ValueError('Setup needs a terminal. Supply explicit profile flags for a scripted run.') from error


def domain_details(checkout):
    """Describe actual domain alias additions without executing their shell code."""
    entries = tracked(checkout) if checkout is not None else {}
    lines = ['Your domain chooses optional additions from the content repository.',
             'Git identity and tool versions are chosen separately.', '']
    if checkout is not None:
        base = []
        for label, paths in [('shell startup', ['.zshrc', '.bashrc']),
                             ('shared command shortcuts', ['.config/dotfiles/aliases/core.zsh']),
                             ('Git defaults', ['.gitconfig']), ('prompt appearance', ['.config/starship.toml'])]:
            if any(path in entries for path in paths):
                base.append(label)
        if base:
            lines += ['Base files in this checkout: ' + ', '.join(base) + '.', '']
    descriptions = read_toml(checkout / 'dotfleet.toml').get('domains', {}) if checkout else {}
    lines.append('  core      Base configuration only. No domain additions.')
    if descriptions.get('core'):
        lines.append('            ' + descriptions['core'])
    empty = 0
    for domain in ['personal', 'work', 'client']:
        name = f'.config/dotfiles/aliases/{domain}.zsh'
        if entries.get(name) not in ('100644', '100755'):
            summary = 'Additions are not described here. Check the content repository documentation.'
        else:
            content = run('git', '-C', str(checkout), 'show', ':' + name)
            active = [line for line in content.splitlines() if line.strip() and not line.lstrip().startswith('#')]
            if not active:
                summary = 'Adds nothing yet. Add your own settings here.'
                empty += 1
            else:
                names = re.findall(r'^\s*alias\s+([A-Za-z_][A-Za-z_0-9-]*)=', content, re.M)
                names += re.findall(r'^\s*([A-Za-z_][A-Za-z_0-9-]*)\s*\(\)\s*\{', content, re.M)
                summary = 'Command names: ' + ', '.join(dict.fromkeys(names)) + '.' if names else 'Contains custom shell settings.'
                summary += f' Review .config/dotfiles/aliases/{domain}.zsh for their behavior.'
        lines.append(f'  {domain:<9} {summary}')
        if descriptions.get(domain):
            lines.append('            ' + descriptions[domain])
    if empty == 3:
        lines += ['', 'Personal, work, and client currently add no domain commands. Start with core.']
    lines += ['', 'Names describe intended use: personal for yourself, work for an employer, client for a customer.',
              'Choosing a domain does not install software or create accounts.',
              'Your choice is saved in ~/.config/dotfleet/profile.toml.',
              'The default is core for a new profile, or your saved domain on later runs.',
              '', 'Press Enter to confirm the value in brackets, or type a domain name and press Enter.',
              'Type skip and press Enter to keep the value without confirming it.']
    return '\n'.join(lines)


def repo_id(url):
    return url.removesuffix('.git').rstrip('/').replace('git@github.com:', 'https://github.com/').replace('ssh://git@github.com/', 'https://github.com/')


def old_profile(home):
    data = read_toml(home / '.config/chezmoi/chezmoi.toml').get('data', {})
    pins = dict(data.get('miseTools', {}))
    current_mise = read_toml(home / '.config/mise/config.toml')
    current = current_mise.get('tools', {})
    pins.update(current)
    saved = read_toml(home / '.config/dotfiles/profile.toml')
    pins.update(saved.get('miseTools', saved.get('tool_pins', saved.get('pins', saved.get('tools', {})))))
    profile = {
        'content_repo': saved.get('content_repo', DEFAULT_REPO),
        'domain': saved.get('domain', data.get('domain', 'core')),
        'git_name': saved.get('git_name', saved.get('gitName', data.get('gitName', ''))),
        'git_email': saved.get('git_email', saved.get('gitEmail', data.get('gitEmail', ''))),
        'pins': pins, 'groups': saved.get('groups', {}),
    }
    # Carry-over is not evidence of a choice in this wizard.
    profile['domain_chosen'] = False
    if 'settings' in current_mise:
        profile['mise_settings'] = current_mise['settings']
    if data.get('secretsEnabled'):
        profile['secrets'] = {'EXAMPLE_API_TOKEN': {'enabled': True, 'reference': data['secretReference']}}
    if saved.get('secrets'):
        profile['secrets'] = saved['secrets']
    sources = []
    if data:
        sources.append('old chezmoi data')
    if current:
        sources.append('current Mise tools')
    if saved:
        sources.append('saved installer profile')
    return profile, sources


def reconcile_config_template_state():
    """Acknowledge templates without letting them write the manager's config."""
    # source-path accounts for a native repository's .chezmoiroot.
    source = Path(run('chezmoi', 'source-path').strip())
    templates = [source / f'.chezmoi.{extension}.tmpl'
                 for extension in ('json', 'jsonc', 'toml', 'yaml', 'yml')
                 if (source / f'.chezmoi.{extension}.tmpl').exists()]
    if len(templates) > 1:
        raise ValueError('Multiple chezmoi config templates exist; keep only one in the content repository.')
    # Match chezmoi's configState record. Leave file and script history intact.
    # https://github.com/twpayne/chezmoi/blob/v2.74.1/internal/cmd/config.go
    args = ['chezmoi', 'state']
    if templates:
        state = {'configTemplateContentsSHA256': hashlib.sha256(templates[0].read_bytes()).hexdigest()}
        run(*args, 'set', '--bucket=configState', '--key=configState', '--value=' + json.dumps(state))
    else:
        run(*args, 'delete', '--bucket=configState', '--key=configState')


def exact_version(version):
    """Require a full numeric release or a complete Git commit identifier."""
    return isinstance(version, str) and bool(re.fullmatch(
        r'(?:[A-Za-z][A-Za-z0-9_-]*-)?v?\d+(?:\.\d+){2,}(?:[a-zA-Z][0-9A-Za-z._-]*|[-+][0-9A-Za-z][0-9A-Za-z.+-]*)?'
        r'|\d{4}-\d{2}-\d{2}|[0-9a-f]{40}', version))


def resolve_installed_pin(home, tool, request):
    result = subprocess.run(['mise', 'latest', '--installed', '--cd', str(home), f'{tool}@{request}'],
                            text=True, capture_output=True)
    version = result.stdout.strip()
    return version if result.returncode == 0 and exact_version(version) else None


def has_terminal():
    try:
        descriptor = os.open('/dev/tty', os.O_RDWR)
    except OSError:
        return False
    os.close(descriptor)
    return True


def profile_gaps(profile):
    gaps = []
    if not profile.get('domain_chosen', False):
        gaps.append(f"Domain was never explicitly chosen (recorded: {profile.get('domain', 'core')}). Supply --domain.")
    for field, label, flag in [('git_name', 'Git name', '--git-name'), ('git_email', 'Git email', '--git-email')]:
        if not profile.get(field, '').strip():
            gaps.append(f'{label} is empty. Supply {flag}.')
    for tool, request in profile.get('pins', {}).items():
        for item in request if isinstance(request, list) else [request]:
            version = item.get('version', '') if isinstance(item, dict) else item
            if not exact_version(version):
                gaps.append(f'{tool} pin is floating (recorded: {version}). Supply --pin {tool}=VERSION with a full version.')
    return gaps


def require_complete_profile(profile):
    gaps = profile_gaps(profile)
    if gaps:
        raise ValueError('Non-interactive setup needs a complete profile:\n- ' + '\n- '.join(gaps)
                         + '\nProvide these flags, or run in a terminal without --defaults.')


def pin_argument(text):
    tool, separator, version = text.partition('=')
    if not separator or not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9:._@/-]*', tool) or not version.strip():
        raise argparse.ArgumentTypeError('--pin needs TOOL=VERSION, for example node=24.14.1')
    return tool, version.strip()


def group_argument(text):
    name, separator, choice = text.partition('=')
    if not separator or not name or choice not in ('on', 'off'):
        raise argparse.ArgumentTypeError('--group needs NAME=on or NAME=off')
    return name, choice


def validate_profile(home, profile, defaults=False, configure=False, checkout=None):
    """Ask about gaps and return warnings for choices left incomplete."""
    warnings = []
    if defaults:
        require_complete_profile(profile)
    # Old core defaults have no proof of an explicit choice. Ask once and record it.
    profile.setdefault('domain_chosen', False)
    if not defaults and (configure or not profile['domain_chosen']):
        domain = ask('Domain', profile.get('domain', 'core'), ['core', 'personal', 'work', 'client', 'skip'], defaults,
                     heading='Choose your domain', detail=domain_details(checkout))
        if domain != 'skip':
            profile['domain'] = domain
            if not defaults:
                profile['domain_chosen'] = True
    if not profile['domain_chosen']:
        warnings.append('No domain choice confirmed. The recorded domain remains in use.')
    if not defaults and (configure or not profile.get('git_name', '').strip() or not profile.get('git_email', '').strip()):
        for field, label in [('git_name', 'Git author name'), ('git_email', 'Git author email')]:
            recorded = profile.get(field, '')
            answer = ask(label, recorded, defaults=defaults, heading='Git commit identity',
                         detail='Git records this value on commits.\nPress Enter to keep the shown value, or type skip to leave it unchanged.')
            if answer != 'skip':
                profile[field] = answer
    if not profile.get('git_name', '').strip() or not profile.get('git_email', '').strip():
        warnings.append('No complete git identity recorded. Git commits will fail until one is set.')
    pins = profile.setdefault('pins', {})
    unpinned = set(profile.get('unpinned_tools', []))
    for tool, request in list(pins.items()):
        entries = request if isinstance(request, list) else [request]
        resolved = []
        for item in entries:
            version = item.get('version', '') if isinstance(item, dict) else item
            if not exact_version(version):
                recorded = str(version)
                installed = resolve_installed_pin(home, tool, recorded)
                action = f'uses installed {installed}' if installed else 'leaves this tool unpinned; no matching version is installed'
                label = f'{tool} pin'
                detail = f'Recorded value: {recorded}.\nPress Enter: {action}.\nType a full version (for example 24.14.1), or skip to leave it unpinned. Press Enter to submit.'
                while True:
                    answer = ask(label, recorded, defaults=defaults, heading='Choose an exact tool version', detail=detail)
                    if answer == 'skip':
                        version = None
                        break
                    if answer == recorded:
                        version = installed
                        break
                    if exact_version(answer):
                        version = answer
                        break
                    print('Use a full version, such as 24.14.1, or type skip.')
                if version is None:
                    warnings.append(f'{tool}: skipped floating pin {recorded}. No version was recorded for this entry.')
                    continue
                print(f'Recorded exact pin: {tool} = {version}')
            resolved.append(dict(item, version=version) if isinstance(item, dict) else version)
        if resolved:
            unpinned.discard(tool)
            pins[tool] = resolved if isinstance(request, list) else resolved[0]
        else:
            del pins[tool]
            unpinned.add(tool)
    if unpinned or 'unpinned_tools' in profile:
        profile['unpinned_tools'] = sorted(unpinned)
    for tool in sorted(unpinned):
        warnings.append(f'{tool} is unpinned. Content defaults will not select it.')
    return warnings


def select_profile(home, args, workspace):
    import enrollment as wizard
    path = home / '.config/dotfleet/profile.toml'
    exists = path.exists()
    profile, sources = (read_toml(path), ['existing Dotfleet profile']) if exists else old_profile(home)
    profile.setdefault('domain_chosen', False)
    if args.domain is not None:
        profile.update(domain=args.domain, domain_chosen=True)
    for field in ('git_name', 'git_email'):
        if getattr(args, field) is not None:
            profile[field] = getattr(args, field).strip()
    for tool, version in args.pin:
        previous = profile.setdefault('pins', {}).get(tool)
        profile['pins'][tool] = dict(previous, version=version) if isinstance(previous, dict) else version
    unattended = args.defaults or not has_terminal()
    args.wizard = not unattended and (not exists or bool(profile_gaps(profile)) or args.configure or args.adopt)
    profile.setdefault('pins', {})
    profile.setdefault('secrets', {})
    if args.wizard:
        args.found, args.excluded = wizard.welcome(home, sources)
        profile, checkout, manifest, warnings = wizard.steps(home, args, workspace, profile, args.found, args.excluded)
        return profile, sources, checkout, manifest, warnings
    if getattr(args, 'edit', None):
        args.edit(profile)
    require_complete_profile(profile)
    repo = args.repo or profile.get('content_repo', DEFAULT_REPO)
    if args.adopt:
        found, excluded = wizard.scan(home)
        for name, reason in excluded.items():
            print(f'Excluded from adoption: {name} ({reason})')
        checkout = wizard.adopt(home, workspace, found, excluded)
        repo = str(home / 'dotfiles')
        profile.update(adopted=True, adoption_excluded=sorted(excluded), source_door='adopt')
    else:
        checkout = wizard.stage_repo(home, repo, workspace)
    kind, manifest = detect(checkout, args.format or profile.get('format'))
    profile.update(content_repo=repo, format=kind, adopted=bool(manifest.get('adopted', False)))
    warnings = validate_profile(home, profile, True, checkout=checkout)
    wizard.group_flags(profile, args.group, manifest)
    selections = profile.setdefault('groups', {})
    for group, spec in manifest.get('groups', {}).items():
        if group not in selections:
            choice = ask(group, 'on', ['on', 'off'], unattended,
                         detail=f'{spec["description"]}. on: include; off: exclude. Press Enter to submit.')
            if unattended:
                print(f'Group {group}: using {choice} ({spec["description"]}).')
            selections[group] = choice == 'on'
    if args.agents is not None:
        wizard.agent_flags(profile, args.agents)
    profile.setdefault('agents', {name: False for name in wizard.agent_manifest()})
    return profile, sources, checkout, manifest, warnings


def installed_defaults(defaults, pins, home):
    installed = json.loads(run('mise', 'ls', '--installed', '--json', '--cd', str(home)))
    effective = dict(pins)
    available = {}
    for tool, request in defaults.items():
        if tool in pins:
            continue
        if not installed.get(tool):
            available[tool] = request
            continue
        requests = request if isinstance(request, list) else [request]
        matches = []
        for item in requests:
            version = item.get('version', '') if isinstance(item, dict) else item
            if not isinstance(version, str) or not version:
                matches.append(False)
                continue
            resolved = resolve_installed_pin(home, tool, version)
            matches.append(dict(item, version=resolved) if isinstance(item, dict) and resolved else resolved)
        if all(matches):
            effective[tool] = matches if isinstance(request, list) else matches[0]
        else:
            available[tool] = request
    return effective, available


def fingerprint(path):
    if path.is_symlink():
        return {'link': os.readlink(path)}
    if path.is_file():
        return {'sha256': hashlib.sha256(path.read_bytes()).hexdigest(), 'mode': path.stat().st_mode & 0o777}
    return None


def backup_location(home):
    root = home / 'dotfleet-backups'
    stamp = datetime.datetime.now().strftime('%Y%m%d-%H%M%S')
    destination = root / stamp
    suffix = 0
    while destination.exists():
        suffix += 1
        destination = root / f'{stamp}-{suffix}'
    return destination


def backup_inventory(home, paths):
    entries = []
    for name in sorted(set(paths)):
        path = home / relative(name)
        if not path.parent.resolve().is_relative_to(home.resolve()):
            raise ValueError(f'Managed parent leaves HOME: {name}')
        if not path.exists() and not path.is_symlink():
            entries.append({'path': name, 'state': 'absent'})
            continue
        item = {'path': name, 'state': 'saved', 'fingerprint': fingerprint(path)}
        if path.is_symlink():
            item['link'] = os.readlink(path)
            resolved = path.resolve()
            if resolved.is_file() and not resolved.is_relative_to(home.resolve()):
                item['external'] = str(resolved)
        entries.append(item)
    return entries


def backup(home, paths, destination=None):
    entries = backup_inventory(home, paths)
    destination = destination or backup_location(home)
    destination.parent.mkdir(exist_ok=True, mode=0o700)
    destination.mkdir(mode=0o700)
    for item in entries:
        if item['state'] == 'absent':
            continue
        path = home / item['path']
        target = destination / 'home' / item['path']
        target.parent.mkdir(parents=True, exist_ok=True)
        if path.is_symlink():
            target.symlink_to(os.readlink(path))
        elif path.is_dir():
            shutil.copytree(path, target, symlinks=True, dirs_exist_ok=True)
        else:
            shutil.copy2(path, target)
        if 'external' in item:
            external = destination / 'external' / item['external'].lstrip('/')
            external.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(item['external'], external)
    atomic(destination / 'MANIFEST.json', json.dumps(entries, indent=2) + '\n')
    return destination


def generated_files(home, profile, manifest, defaults):
    allowed_defaults = {tool: version for tool, version in defaults.get('tools', {}).items()
                        if tool not in profile.get('unpinned_tools', [])}
    pins, available = installed_defaults(allowed_defaults, profile['pins'], home)
    mise = dict(defaults)
    mise['tools'] = pins
    if 'mise_settings' in profile:
        mise['settings'] = profile['mise_settings']
    mise.setdefault('settings', {})
    mise['settings'].setdefault('experimental', False)
    with tempfile.TemporaryDirectory() as folder:
        local = Path(folder) / 'local.gitconfig'
        previous = home / '.config/git/local.gitconfig'
        local.write_bytes(previous.read_bytes() if previous.is_file() else b'# Machine settings generated by Dotfleet.\n')
        for key, field in [('user.name', 'git_name'), ('user.email', 'git_email')]:
            subprocess.run(['git', 'config', '--file', str(local), '--unset-all', key], capture_output=True)
            if profile.get(field):
                run('git', 'config', '--file', str(local), key, profile[field])
        identity = local.read_bytes()
    references = dict(manifest.get('secrets', {}))
    references.update(profile.get('secrets', {}))
    active = {key: item for key, item in references.items() if item.get('enabled')}
    if active:
        lines = ['# Generated by Dotfleet. Never commit secret values.']
        for key, item in sorted(active.items()):
            if not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', key) or not item['reference'].startswith('op://'):
                raise ValueError('Secret entries need a shell variable name and an op:// reference.')
            secret = run('op', 'read', '--no-newline', item['reference'])
            lines.append(f'export {key}={shlex.quote(secret)}')
        secrets = ('\n'.join(lines) + '\n').encode()
    else:
        previous = home / '.secrets'
        secrets = previous.read_bytes() if previous.is_file() else PLACEHOLDER
    return {
        '.config/git/local.gitconfig': identity,
        '.config/dotfiles/domain': (profile['domain'] + '\n').encode(),
        '.config/mise/config.toml': toml(mise).encode(),
        '.secrets': secrets,
    }, pins, available


def prepare(home, checkout, profile, manifest, folder):
    import enrollment as wizard
    import agent_configs
    folder.mkdir()
    defaults = wizard.content_defaults(checkout)
    generated, pins, available = generated_files(home, profile, manifest, defaults)
    source, items, _ = convert(checkout, folder / 'source', profile, profile['format'])
    native = items is None
    old_config = read_toml(home / '.config/chezmoi/chezmoi.toml')
    data = dict(old_config.get('data', {}))
    data.update(domain=profile['domain'], gitName=profile.get('git_name', ''), gitEmail=profile.get('git_email', ''), miseTools=pins)
    config = {'sourceDir': str(source), 'destDir': str(home), 'umask': 0o077, 'data': data}
    config_path = folder / 'preview.toml'
    atomic(config_path, toml(config))
    command = ['chezmoi', '--config', str(config_path), '--persistent-state', str(folder / 'state.db'),
               '--cache', str(folder / 'cache')]
    if native:
        names = set(filter(None, run(*command, 'managed', '--include', 'files,symlinks', '--path-style', 'relative', '-0').split('\0')))
        if names & GENERATED:
            raise ValueError('Native content owns a manager-reserved path: ' + ', '.join(sorted(names & GENERATED)))
    else:
        names = set(items)
        for name, content in list(generated.items()):
            if profile.get('adopted') and name in items:
                # Adoption preserves authored bytes, including existing Mise settings.
                del generated[name]
                if name == '.config/mise/config.toml':
                    pins = defaults.get('tools', {})
                continue
            if name in items:
                _, mode = items[name]
                authored = source / source_name(name, mode)
                for old_target in (authored, authored.with_name('empty_' + authored.name)):
                    if old_target.exists() or old_target.is_symlink():
                        old_target.unlink()
            target = source / source_name(name)
            if name == '.secrets':
                target = target.with_name('private_' + target.name)
            atomic(target, content)
        names |= set(generated)
    private_state = names & {'.local/share/dotfleet/fleet.toml', '.config/dotfleet/profile.toml'}
    if private_state:
        raise ValueError('Content cannot own manager state: ' + ', '.join(sorted(private_state)))
    state_path = home / '.local/state/dotfleet/outputs.json'
    previous = json.loads(state_path.read_text()) if state_path.exists() else {}
    stale = set(previous) - names - set(generated)
    for name in stale:
        if fingerprint(home / name) not in (None, previous[name]):
            raise ValueError(f'Excluded output has local edits; preserve it before applying: {name}')
    # Status reads destination files but writes its cache and state only in scratch.
    changes = run(*command, 'status', '--include', 'files,symlinks', '--path-style', 'relative')
    diff_path = folder / 'chezmoi.diff'
    atomic(diff_path, run(*command, '--no-pager', '--use-builtin-diff', '--color=false', 'diff', '--include', 'files,symlinks'))
    changed = {line[3:] for line in changes.splitlines() if len(line) > 3 and line[1] != ' '}
    removed = {line[3:] for line in changes.splitlines() if len(line) > 3 and line[1] == 'D'}
    for name, content in generated.items():
        path = home / name
        if not path.is_file() or path.read_bytes() != content or path.stat().st_mode & 0o777 != 0o600:
            changed.add(name)
    agents = agent_configs.generate(home, agent_configs.native_os(), True, profile=profile, content_root=checkout) if any(profile.get('agents', {}).values()) else {}
    changed |= {name for name, item in agents.items() if not fingerprint(home / name) or any(fingerprint(home / name).get(key) != value for key, value in item.items())}
    changed |= {name for name in stale if fingerprint(home / name) is not None}
    controls = {'.local/share/dotfleet/fleet.toml', '.config/chezmoi/chezmoi.toml', '.config/dotfleet/profile.toml', '.local/state/dotfleet/outputs.json', '.local/state/dotfleet/last-run.json'}
    stable_source = home / 'dotfiles' if native else home / '.local/share/dotfleet/chezmoi-source'
    final_config = {'sourceDir': str(stable_source), 'umask': 0o077, 'data': data}
    for name, content in [('.config/chezmoi/chezmoi.toml', toml(final_config)), ('.config/dotfleet/profile.toml', toml(profile))]:
        path = home / name
        matches = (read_toml(path) == profile) if name == '.config/dotfleet/profile.toml' and path.is_file() else path.is_file() and path.read_text() == content
        if not matches or path.is_symlink() or path.stat().st_mode & 0o777 != 0o600:
            changed.add(name)
    # Output inventories are bookkeeping, not rendered home settings.
    all_paths = names | set(generated) | stale | controls | set(agents) | changed | removed
    for tool in ['chezmoi', 'mise']:
        if os.environ.get('DOTFLEET_STAGED_' + tool.upper()):
            all_paths.add('.local/bin/' + tool)
            changed.add('.local/bin/' + tool)
    from installation import COMMAND, launcher
    all_paths.add(COMMAND)
    target = home / COMMAND
    if not target.is_file() or target.read_bytes() != launcher(ROOT) or target.stat().st_mode & 0o777 != 0o700:
        changed.add(COMMAND)
    if agents:
        all_paths.add('.local/state/dotfleet/agents.json')
        changed.add('.local/state/dotfleet/agents.json')
    return dict(source=source, native=native, names=names, generated=generated, pins=pins, available=available,
                stale=stale, all_paths=all_paths, changed=changed, config=final_config, agents=agents,
                removed=removed, diff_path=diff_path, status=changes,
                baseline={name: fingerprint(home / name) for name in all_paths})


def publish_checkout(home, checkout, profile, backup_path):
    canonical = home / 'dotfiles'
    if canonical.exists():
        # Recheck local edits after review. Fetch exactly the reviewed commit, never a newer remote tip.
        if run('git', '-C', str(canonical), 'status', '--porcelain').strip():
            raise ValueError('Content changed during review. Preserve edits and run setup again.')
        commit = run('git', '-C', str(checkout), 'rev-parse', 'HEAD').strip()
        if profile.get('source_door') == 'adopt' and not subprocess.run(
                ['git', '-C', str(checkout), 'config', '--get', 'remote.origin.url'], capture_output=True).stdout:
            canonical.rename(backup_path / 'previous-content')
            shutil.copytree(checkout, canonical, symlinks=True)
        else:
            run('git', '-C', str(canonical), 'fetch', str(checkout), commit)
            run('git', '-C', str(canonical), 'merge', '--ff-only', commit)
    else:
        shutil.copytree(checkout, canonical, symlinks=True)
    # A newly adopted repository intentionally has no remote or saved credentials.
    if profile.get('adopted'):
        print('Adopted repository: ~/dotfiles. Create an empty remote, then run git remote add origin URL and git push -u origin main.')
    return canonical


def main(argv=None, edit=None, software=None, before_apply=None):
    import enrollment as wizard
    import agent_configs
    from run_account import RunAccount, RECORD
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter,
                                     epilog='Version: ' + (ROOT / 'VERSION').read_text().strip())
    doors = parser.add_mutually_exclusive_group()
    doors.add_argument('--repo', help='content Git URL or absolute local repository')
    doors.add_argument('--adopt', action='store_true', help='seed a local repository from scanned home files; exclude secret matches')
    parser.add_argument('--configure', action='store_true', help='review all wizard steps with saved choices')
    parser.add_argument('--defaults', action='store_true', help='use recorded complete values without prompts; new groups default on')
    parser.add_argument('--domain', choices=['core', 'personal', 'work', 'client'], help='record a human domain choice; content defines its additions')
    parser.add_argument('--git-name', help='Git author name; required when missing without a terminal')
    parser.add_argument('--git-email', help='Git author email; required when missing without a terminal')
    parser.add_argument('--pin', action='append', type=pin_argument, default=[], metavar='TOOL=VERSION', help='record an exact version; repeat for more tools')
    parser.add_argument('--group', action='append', type=group_argument, default=[], metavar='NAME=on|off', help='include or exclude a named content group; repeat for more groups')
    parser.add_argument('--agents', help='comma-separated detected agent names, or none to skip configuration')
    parser.add_argument('--format', choices=['plain', 'chezmoi'], help='plain=real names; chezmoi=native sources')
    args = parser.parse_args(argv)
    args.edit = edit
    home = Path.home()
    # Git status must not refresh the real checkout's index before confirmation.
    os.environ['GIT_OPTIONAL_LOCKS'] = '0'
    backup_path = 'not created'
    account = None
    writes_started = False
    warnings = []
    try:
        with tempfile.TemporaryDirectory(prefix='dotfleet-plan-') as temporary:
            workspace = Path(temporary)
            # Tool queries must not populate the real home's cache before confirmation.
            original_data = Path(os.environ.get('MISE_DATA_DIR', str(Path(os.environ.get('XDG_DATA_HOME', str(home / '.local/share'))) / 'mise')))
            os.environ.setdefault('MISE_INSTALLS_DIR', str(original_data / 'installs'))
            os.environ.setdefault('MISE_PLUGINS_DIR', str(original_data / 'plugins'))
            os.environ['MISE_DATA_DIR'] = str(workspace / 'mise-data')
            os.environ['MISE_CACHE_DIR'] = str(workspace / 'mise-cache')
            os.environ['MISE_STATE_DIR'] = str(workspace / 'mise-state')
            account = RunAccount(home, ROOT)
            if software:
                account.software.extend(software)
            profile, carried, checkout, manifest, warnings = select_profile(home, args, workspace)
            print('Carried from: ' + (', '.join(carried) or 'new profile'))
            attempt = 0
            while True:
                plan = prepare(home, checkout, profile, manifest, workspace / f'plan-{attempt}')
                proposed_backup = backup_location(home)
                account.plan(plan, checkout, profile, proposed_backup, backup_inventory(home, plan['all_paths']))
                if not args.wizard:
                    break
                choice = wizard.review(profile, account, warnings)
                if choice == 'quit':
                    account.finish('CANCELLED', warnings)
                    return 0
                if choice == 'confirm':
                    break
                # Going back permits edits even when the original step had a flag.
                for field in {'source': ['repo', 'adopt'], 'domain': ['domain'], 'identity': ['git_name', 'git_email'],
                              'pins': ['pin'], 'groups': ['group'], 'agents': ['agents']}[choice]:
                    setattr(args, field, [] if field in ('pin', 'group') else False if field == 'adopt' else None)
                profile, checkout, manifest, warnings = wizard.steps(home, args, workspace, profile, args.found, args.excluded,
                                                                    wizard.STEPS.index(choice), checkout, manifest)
                attempt += 1
            if any(fingerprint(home / name) != before for name, before in plan['baseline'].items()):
                raise ValueError('Home files changed during review. Nothing applied; run setup again to review those changes.')
            backup_path = backup(home, plan['all_paths'], proposed_backup)
            account.bind_backup(backup_path)
            writes_started = True
            if os.environ.get('DOTFLEET_APPLY_MARKER'):
                Path(os.environ['DOTFLEET_APPLY_MARKER']).touch()
            print(f'Backup: {backup_path}', flush=True)
            checkout = publish_checkout(home, checkout, profile, backup_path)
            account.applied_checkouts.add('Content')
            account.save()
            from installation import publish
            publish(home, ROOT, backup_path)
            account.applied_checkouts.add('Manager')
            atomic(home / RECORD, json.dumps({'manager_commit': account.checkouts[0]['new']}) + '\n')
            account.applied_software.add('dotfleet')
            if before_apply:
                before_apply(account)
            account.save()
            # Temporary downloads become local tools only after review and backup.
            for tool in ['chezmoi', 'mise']:
                supplied = os.environ.get('DOTFLEET_STAGED_' + tool.upper())
                if supplied:
                    atomic(home / '.local/bin' / tool, Path(supplied).read_bytes(), 0o700)
                    account.applied_software.add('Mise' if tool == 'mise' else tool)
                    account.save()
            stable_source = Path(plan['config']['sourceDir'])
            if not plan['native']:
                stable_source.parent.mkdir(parents=True, exist_ok=True)
                if stable_source.exists():
                    stable_source.rename(backup_path / 'previous-chezmoi-source')
                shutil.copytree(plan['source'], stable_source, symlinks=True)
            atomic(home / '.config/chezmoi/chezmoi.toml', toml(plan['config']))
            reconcile_config_template_state()
            profile_path = home / '.config/dotfleet/profile.toml'
            if not profile_path.exists() or read_toml(profile_path) != profile:
                atomic(profile_path, toml(profile))
            account.profile_written = True
            account.save()
            if plan['native']:
                for name, content in plan['generated'].items():
                    atomic(home / name, content)
            for name in plan['stale']:
                path = home / name
                if path.exists() or path.is_symlink():
                    retired = backup_path / 'retired' / name
                    retired.parent.mkdir(parents=True, exist_ok=True)
                    path.rename(retired)
                # This deletion was requested by the group selection, not a local edit.
                # Retire only this path's remembered entry; preserve all other conflict state.
                run('chezmoi', 'state', 'delete', '--bucket=entryState', '--key=' + str(path))
            result = subprocess.run(['bash', str(ROOT / 'scripts/apply.sh')])
            account.confirm_files(fingerprint)
            if result.returncode:
                raise RuntimeError(f'chezmoi apply failed with exit {result.returncode}; restore from {backup_path}')
            if any(profile.get('agents', {}).values()):
                agent_configs.generate(home, agent_configs.native_os(), False)
            account.confirm_files(fingerprint)
            status = run('chezmoi', 'status')
            if status.strip():
                raise ValueError('Managed files still differ:\n' + status)
            names = plan['names'] | set(plan['generated'])
            atomic(home / '.local/state/dotfleet/outputs.json', json.dumps({name: fingerprint(home / name) for name in sorted(names)}, indent=2) + '\n')
            return account.finish('SUCCESS', warnings, 'CLEAN (no differences)')
    except (OSError, ValueError, RuntimeError, KeyError) as error:
        print(f'Setup failed: {error}', file=sys.stderr)
        if account:
            if writes_started:
                account.confirm_files(fingerprint)
            account.finish('FAILED', [*warnings, str(error)])
        return 1


