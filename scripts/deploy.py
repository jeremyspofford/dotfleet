"""Deploy Fleet to another machine over SSH and register both machines with each other.

SSH is the secure connection tool. The deploy uses the caller's SSH config and keys.
Every remote shell command is fixed. Values travel through standard input, never in a command.

Usage: fleet machines install NAME [--target user@host] [--return-target TARGET]
Steps: probe the target, bootstrap Python when needed, enroll it, register both ways, prove the loop.
Help: python3 scripts/deploy.py --help.
"""

import datetime
import json
import os
from pathlib import Path
import re
import subprocess
import sys

import connections
import registry
import remote

RAW = "https://raw.githubusercontent.com/jeremyspofford/fleet/main"
STAGE = ".cache/fleet-deploy"
FLOOR = ("bash", "curl", "git", "tar", "gzip")
DIGEST = ("sha256sum", "shasum")  # The Mise installer verifies its download with either one.
PYTHON_FLOOR = (3, 11)

# Each script below is the whole remote program. It reads no caller value from its command line.
PROBE = r"""
os=$(uname -s); wsl=no
if [ "$os" = Linux ] && grep -qi microsoft /proc/version 2>/dev/null; then wsl=yes; fi
echo "os=$os"
echo "wsl=$wsl"
for tool in bash curl git tar gzip sha256sum shasum python3; do
	if command -v "$tool" >/dev/null 2>&1; then echo "have_$tool=yes"; else echo "have_$tool=no"; fi
done
if command -v python3 >/dev/null 2>&1; then
	echo "python=$(python3 -c 'import sys; print("%d.%d" % sys.version_info[:2])' 2>/dev/null)"
fi
if [ -x "$HOME/.local/share/fleet/python/bin/python3" ]; then echo "fleet_python=yes"; fi
# curl exits 77 or 60 when no CA certificate bundle can verify HTTPS.
if command -v curl >/dev/null 2>&1; then
	curl -fsS --max-time 10 -o /dev/null https://github.com 2>/dev/null
	echo "https_code=$?"
fi
for manager in apt-get dnf yum pacman zypper apk brew; do
	if command -v "$manager" >/dev/null 2>&1; then echo "packager=$manager"; break; fi
done
"""
BOOTSTRAP = r"""
set -eu
mise="$HOME/.local/bin/mise"
if [ ! -x "$mise" ]; then
	mkdir -p "$HOME/.local/bin"
	curl -fsSL https://mise.run | MISE_INSTALL_PATH="$mise" sh >&2
fi
# A separate Mise store keeps Fleet's Python apart from the user's own tool versions.
data="$HOME/.local/share/fleet/mise"
export MISE_DATA_DIR="$data" MISE_CACHE_DIR="$data/cache" MISE_CONFIG_DIR="$data/config"
export MISE_STATE_DIR="$data/state"
"$mise" install python@3.12 >&2
folder=$("$mise" where python@3.12)
mkdir -p "$HOME/.local/share/fleet"
ln -sfn "$folder" "$HOME/.local/share/fleet/python"
"$HOME/.local/share/fleet/python/bin/python3" -c 'import sys; print("python=%d.%d" % sys.version_info[:2])'
"""
RUN_SCRIPT = r"""#!/usr/bin/env bash
# Generated by Fleet's deploy. Run the Fleet installer with the caller's validated arguments.
set -euo pipefail
stage="$HOME/.cache/fleet-deploy"
export PATH="$HOME/.local/share/fleet/python/bin:$HOME/.local/bin:$PATH"
arguments=()
if [[ -s $stage/arguments ]]; then mapfile -d '' arguments < "$stage/arguments"; fi
if [[ -s $stage/manager ]]; then
	# Tests and containers can name a local manager checkout instead of the published one.
	bash "$(cat "$stage/manager")/install.sh" "${arguments[@]}"
else
	curl -fsSL __RAW__/install.sh | bash -s -- "${arguments[@]}"
fi
""".replace("__RAW__", RAW)
STAGED = ("run.sh", "arguments", "manager")


def stage_command(name):
    """Return the fixed command that saves one staged file from standard input."""
    assert name in STAGED
    folder = '"$HOME/' + STAGE + '"'
    return f"umask 077 && mkdir -p {folder} && cat > {folder}/{name}"


RUN_COMMAND = 'bash "$HOME/' + STAGE + '/run.sh"'


class DeployError(Exception):
    """A deploy failure with its class, its message lines, and its exit code."""

    def __init__(self, kind, lines, code=1):
        super().__init__(lines[0])
        self.kind, self.lines, self.code = kind, lines, code


def install_hint(tool, packager, system):
    """Name the one command that installs a missing floor item."""
    package = "coreutils" if tool in DIGEST else tool
    if tool == "ca-certificates" and packager == "brew":
        return "brew install ca-certificates"
    if system == "Darwin" and tool == "git" and packager != "brew":
        return "xcode-select --install"
    commands = {
        "apt-get": f"sudo apt-get install -y {package}",
        "dnf": f"sudo dnf install -y {package}",
        "yum": f"sudo yum install -y {package}",
        "pacman": f"sudo pacman -S --noconfirm {package}",
        "zypper": f"sudo zypper install -y {package}",
        "apk": f"sudo apk add {package}",
        "brew": f"brew install {package}",
    }
    return commands.get(packager, f"install {package} with the system package manager")


def parse(text):
    facts = {}
    for line in text.splitlines():
        key, separator, value = line.partition("=")
        if separator:
            facts[key.strip()] = value.strip()
    return facts


def python_ready(facts):
    if facts.get("fleet_python") == "yes":
        return True
    version = facts.get("python", "")
    if not re.fullmatch(r"\d+\.\d+", version):
        return False
    return tuple(int(part) for part in version.split(".")) >= PYTHON_FLOOR


def call(name, target, command, payload=""):
    """Run one fixed command. A lost connection is the unreachable class."""
    try:
        result = connections.invoke(target, command, payload)
    except (OSError, subprocess.TimeoutExpired) as error:
        raise DeployError("unreachable", [f"{name}: {connections.one_line(str(error))}"], 2)
    if result.returncode == 255:
        detail = connections.one_line(result.stderr) or "SSH connection failed"
        raise DeployError("unreachable", [f"{name}: {detail}"], 2)
    return result


def probe(home, name, target):
    """Connect in batch mode, detect the system, and check the floor."""
    try:
        result = connections.invoke(target, "sh -s", PROBE, probe=True)
    except (OSError, subprocess.TimeoutExpired) as error:
        reason, step = connections.failure(home, name, target, error)
        raise DeployError("unreachable", [f"{name}: {reason}.", "Next: " + step], 2) from error
    if result.returncode:
        reason, step = connections.failure(home, name, target, ConnectionError(result.stderr))
        raise DeployError("unreachable", [f"{name}: {reason}.", "Next: " + step], 2)
    facts = parse(result.stdout)
    system = "WSL" if facts.get("wsl") == "yes" else facts.get("os", "")
    if system not in ("Linux", "Darwin", "WSL"):
        raise DeployError(
            "missing floor", [f"{name}: Fleet supports Linux, macOS, and WSL, not {system}."], 2
        )
    missing = [tool for tool in FLOOR if facts.get(f"have_{tool}") != "yes"]
    if facts.get("https_code") in ("60", "77"):
        missing.append("ca-certificates")
    if not python_ready(facts) and not any(facts.get(f"have_{tool}") == "yes" for tool in DIGEST):
        missing.append("sha256sum")
    if missing:
        lines = [f"{name}: the target lacks the deploy floor: {', '.join(missing)}."]
        lines += [
            f"  {tool}: {install_hint(tool, facts.get('packager', ''), facts.get('os', ''))}"
            for tool in missing
        ]
        lines.append("Fleet installs no system packages and uses no admin rights.")
        raise DeployError("missing floor", lines, 2)
    facts["system"] = "macOS" if system == "Darwin" else system
    return facts


def bootstrap(name, target, facts):
    """Install Mise and Python 3.12 in the user's own folders when Python is too old."""
    if python_ready(facts):
        return False
    found = facts.get("python") or "none"
    print(
        f"{name}: Python 3.11 or newer is missing (found {found}). Installing Python 3.12 with Mise."
    )
    result = call(name, target, "sh -s", BOOTSTRAP)
    if result.returncode or not python_ready(parse(result.stdout)):
        detail = connections.one_line(result.stderr)[-300:]
        raise DeployError(
            "enrollment failed", [f"{name}: the Python bootstrap failed. {detail}".strip()]
        )
    return True


def installer_arguments(options, scripted):
    words = []
    for flag, value in (
        ("--domain", options.domain),
        ("--git-name", options.git_name),
        ("--git-email", options.git_email),
    ):
        if value:
            words += [flag, value]
    for tool, version in options.tool:
        words += ["--tool", f"{tool}={version}"]
    if options.repo:
        words += ["--repo", options.repo]
    if scripted:
        words.append("--defaults")
    return words


def scripted_gaps(options):
    return [
        flag
        for value, flag in (
            (options.domain, "--domain"),
            (options.git_name, "--git-name"),
            (options.git_email, "--git-email"),
        )
        if not value
    ]


def enroll(name, target, options, terminal):
    """Run the installer on the target. A terminal carries its wizard to this terminal."""
    scripted = not terminal or not scripted_gaps(options)
    words = installer_arguments(options, scripted)
    files = {
        "run.sh": RUN_SCRIPT,
        "arguments": "".join(word + "\0" for word in words),
        "manager": os.environ.get("FLEET_DEPLOY_MANAGER", ""),
    }
    for staged, content in files.items():
        if call(name, target, stage_command(staged), content).returncode:
            raise DeployError("enrollment failed", [f"{name}: could not stage the installer."])
    ssh = ["ssh", "-t" if terminal else "-T"]
    for option in connections.OPTIONS:
        ssh += ["-o", option]
    ssh += ["--", target, RUN_COMMAND]
    print(f"{name}: running the Fleet installer on the target.", flush=True)
    stdin = None if terminal else subprocess.DEVNULL
    code = subprocess.run(ssh, stdin=stdin, env=dict(os.environ, LC_ALL="C")).returncode
    if code == 255:
        raise DeployError("unreachable", [f"{name}: the connection closed during enrollment."], 2)
    return code


def remote_json(name, target, request, kind="enrollment failed"):
    """Send one deploy request to the target's manager and read its JSON answer."""
    result = call(name, target, remote.REMOTE_COMMAND, json.dumps(request) + "\n")
    stream = result.stdout.strip().splitlines()
    try:
        answer = json.loads(stream[-1]) if stream else None
    except ValueError:
        answer = None
    if result.returncode or not isinstance(answer, dict):
        detail = connections.one_line(result.stdout + " " + result.stderr)[-300:]
        raise DeployError(kind, [f"{name}: the target's manager answered: {detail}"])
    return answer


def facts_of(name, target):
    """Read the target's own record. Enrolled means its profile exists and the last run succeeded."""
    answer = remote_json(name, target, {"version": 3, "action": "facts"})
    record = answer.get("machine")
    if not isinstance(record, dict):
        raise DeployError("enrollment failed", [f"{name}: the target sent no machine record."])
    return record


def now():
    return datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")


def peer_record(home):
    """Describe this machine for the target's registry."""
    import command

    data = registry.load(home)
    name = registry.machine_name()
    record = data["machines"].get(name) or registry.machine(
        home, (command.ROOT / "VERSION").read_text().strip()
    )
    return {key: record.get(key, "") for key in registry.FIELDS} | {"recorded_at": now()}


def return_target(home, name, options, terminal):
    """Ask once for the SSH target that reaches this machine from the target."""
    if options.return_target:
        return options.return_target
    if not terminal:
        return ""
    import manager

    caller = registry.machine_name()
    detail = (
        f"Type the SSH target that {name} uses to reach {caller}, such as user@host.\n"
        "Type skip, or press Enter, to save the caller without a connection.\n"
        "Press Enter to submit."
    )
    while True:
        answer = manager.ask(
            "Return target", "skip", heading=f"How {name} reaches {caller}", detail=detail
        )
        if answer == "skip":
            return ""
        try:
            return remote.validate_target(answer)
        except ValueError as error:
            print(f"{error} Try again, or type skip.")


def register_caller(home, target, name, options, terminal):
    """Add the target to this machine's registry under the shared lock and backup rules."""
    import command

    facts = facts_of(name, target)
    facts.update(hostname=name, ssh_target=target, recorded_at=now())

    def add(data):
        data["machines"][name] = {
            key: facts.get(key, kind()) for key, kind in registry.FIELDS.items()
        }
        data["machines"][name].update(ssh_target=target, recorded_at=facts["recorded_at"])

    return command.change_registry(home, add)


def install(home, options):
    """Run every deploy step. Return the exit code; print each failure class and its next step."""
    import manager

    terminal = manager.has_terminal()
    name, target = options.name, options.ssh_target
    if not terminal and scripted_gaps(options):
        print(
            "Error: No terminal attached, so the enrollment wizard cannot run. Supply "
            + ", ".join(scripted_gaps(options))
            + " for a scripted deploy."
        )
        return 2
    try:
        facts = probe(home, name, target)
        print(f"{name}: reachable · {facts['system']} · floor present ({', '.join(FLOOR)}).")
        bootstrap(name, target, facts)
        code = enroll(name, target, options, terminal)
        try:
            record = facts_of(name, target)
        except DeployError:
            record = {}
        if not record.get("enrolled") or record.get("result") != "SUCCESS":
            result = record.get("result") or "no record"
            kind = "wizard aborted" if result == "CANCELLED" or code == 0 else "enrollment failed"
            raise DeployError(
                kind,
                [
                    f"{name}: enrollment did not complete (installer exit {code}; result {result}).",
                    "Nothing was registered on either machine.",
                ],
            )
        back = return_target(home, name, options, terminal)
        peer = peer_record(home) | {"ssh_target": back}
        remote_json(name, target, {"version": 3, "action": "join", "peer": peer})
        result = register_caller(home, target, name, options, terminal)
        if result:
            return result
        if back:
            reverse = remote_json(
                name,
                target,
                {"version": 3, "action": "test-return", "name": peer["hostname"]},
                kind="reverse test failed",
            )
            if reverse.get("code"):
                print(f"Warning: reverse test failed: {reverse.get('reason', 'no detail')}.")
                print(f"Next: on {name}, fix SSH access to {back}; the enrollment stands.")
            else:
                print(f"PASS: {name} reaches {peer['hostname']} through {back}.")
        else:
            print(
                f"Note: {name} saved {peer['hostname']} without a connection; no reverse test ran."
            )
        return remote.execute(home, name, "status")  # The status contact also exchanges digests.
    except DeployError as error:
        print(f"Error: deploy failed ({error.kind}).")
        for line in error.lines:
            print(line)
        return error.code


